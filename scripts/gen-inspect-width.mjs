// Generates src/stdlib/inspect_width.inc: the display width of each code point as Node.js computes it for
// util.inspect (internal getStringWidth, ICU East Asian Width / emoji / zero-width rules). console.log uses
// the width to align the columns of grouped arrays.
// Usage: node --expose-internals scripts/gen-inspect-width.mjs > src/stdlib/inspect_width.inc
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { getStringWidth } = require("internal/util/inspect");

const ranges = [];  // [first, last, width] for widths other than 1
let cur = null;
for (let cp = 0x7f; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const w = getStringWidth(String.fromCodePoint(cp), false);
  if (w === 1) { cur = null; continue; }
  if (cur && cur[2] === w && cur[1] === cp - 1) cur[1] = cp;
  else if (cur && cur[2] === w && cur[1] === 0xd7ff && cp === 0xe000) cur[1] = cp;
  else { cur = [cp, cp, w]; ranges.push(cur); }
}
const hex = (n) => "0x" + n.toString(16).toUpperCase();
let out = `// Generated by scripts/gen-inspect-width.mjs from Node.js ${process.version} (ICU ${process.versions.icu},` +
  ` Unicode ${process.versions.unicode}); do not edit.\n` +
  "// Code points >= 0x7F whose util.inspect display width is not 1: {first, last, width}.\n";
for (const [a, b, w] of ranges) out += `{${hex(a)}, ${hex(b)}, ${w}},\n`;
process.stdout.write(out);
