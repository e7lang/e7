// Generates src/stdlib/casemap.inc: the case mappings of String.prototype.toUpperCase / toLowerCase
// (full Unicode, locale-independent, as Node.js / V8 implement them), from the running Node.js.
//   node scripts/gen-casemap.mjs > src/stdlib/casemap.inc
// Tables:
//   kUpper / kLower: runs of code points that map to one code point by a constant delta, every code
//     point (stride 1) or every other one (stride 2)
//   kUpperSpecial / kLowerSpecial: code points that map to several code points (ß -> SS, İ -> i̇)
//   kCased / kCaseIgnorable: the Unicode properties Final_Sigma needs (Σ -> ς at the end of a word)
const MAX = 0x10ffff;
const isSurrogate = (c) => c >= 0xd800 && c <= 0xdfff;

function mappings(fn) {
  const single = new Map(); // cp -> cp
  const special = new Map(); // cp -> [cps]
  for (let c = 0; c <= MAX; c++) {
    if (isSurrogate(c)) continue;
    const s = String.fromCodePoint(c);
    const m = fn(s);
    if (m === s) continue;
    const cps = [...m].map((x) => x.codePointAt(0));
    if (cps.length === 1) single.set(c, cps[0]);
    else special.set(c, cps);
  }
  return { single, special };
}

function runs(single) {
  const cps = [...single.keys()].sort((a, b) => a - b);
  const out = [];
  let i = 0;
  while (i < cps.length) {
    const lo = cps[i];
    const delta = single.get(lo) - lo;
    // try stride 1 and stride 2, keep the longer run
    let best = { len: 1, stride: 1 };
    for (const stride of [1, 2]) {
      let len = 1;
      while (single.get(lo + len * stride) === lo + len * stride + delta) len++;
      if (len > best.len) best = { len, stride };
    }
    out.push({ lo, len: best.len, delta, stride: best.stride });
    // advance past the covered code points (a stride-2 run leaves the ones between for later runs)
    for (let k = 0; k < best.len; k++) single.delete(lo + k * best.stride);
    while (i < cps.length && !single.has(cps[i])) i++;
  }
  // no run may start inside another (a lookup finds the last run starting at or before a code point):
  // split a stride-2 run around the runs that start between its code points
  for (;;) {
    out.sort((a, b) => a.lo - b.lo);
    let split = false;
    for (let k = 1; k < out.length && !split; k++) {
      const p = out[k - 1];
      const end = p.lo + (p.len - 1) * p.stride;
      if (out[k].lo > end) continue;
      const before = Math.floor((out[k].lo - p.lo + p.stride - 1) / p.stride);  // code points of p below out[k].lo
      out.splice(k - 1, 1, { ...p, len: before }, { lo: p.lo + before * p.stride, len: p.len - before, delta: p.delta, stride: p.stride });
      split = true;
    }
    if (!split) break;
  }
  return out.filter((r) => r.len > 0);
}

function propRanges(re) {
  const out = [];
  let start = -1;
  for (let c = 0; c <= MAX + 1; c++) {
    const inside = c <= MAX && !isSurrogate(c) && re.test(String.fromCodePoint(c));
    if (inside && start < 0) start = c;
    if (!inside && start >= 0) { out.push([start, c - 1]); start = -1; }
  }
  return out;
}

const up = mappings((s) => s.toUpperCase());
const low = mappings((s) => s.toLowerCase());
const upRuns = runs(up.single);
const lowRuns = runs(low.single);
const cased = propRanges(/^\p{Cased}$/u);
const ignorable = propRanges(/^\p{Case_Ignorable}$/u);

const hex = (n) => "0x" + n.toString(16).toUpperCase();
let o = "";
o += `// Generated by scripts/gen-casemap.mjs from Node.js ${process.version} (Unicode ${process.versions.unicode}); do not edit.\n`;
o += "// clang-format off\n";
const emitRuns = (name, rs) => {
  o += `static const CaseRun ${name}[] = {\n`;
  for (const r of rs) o += `  {${hex(r.lo)}, ${r.len}, ${r.delta}, ${r.stride}},\n`;
  o += "};\n";
};
const emitSpecial = (name, m) => {
  o += `static const CaseSpecial ${name}[] = {\n`;
  for (const [c, cps] of [...m].sort((a, b) => a[0] - b[0])) {
    if (cps.length > 3 || cps.some((x) => x > 0xffff)) throw new Error("special mapping out of range: " + c);
    o += `  {${hex(c)}, ${cps.length}, {${cps.map(hex).join(", ")}}},\n`;
  }
  o += "};\n";
};
const emitRanges = (name, rs) => {
  o += `static const CaseRange ${name}[] = {\n`;
  for (const [a, b] of rs) o += `  {${hex(a)}, ${hex(b)}},\n`;
  o += "};\n";
};
emitRuns("kUpper", upRuns);
emitRuns("kLower", lowRuns);
emitSpecial("kUpperSpecial", up.special);
emitSpecial("kLowerSpecial", low.special);
emitRanges("kCased", cased);
emitRanges("kCaseIgnorable", ignorable);
o += "// clang-format on\n";
process.stdout.write(o);
