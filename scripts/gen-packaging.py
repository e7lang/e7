#!/usr/bin/env python3
"""Generates the Homebrew formula (e7.rb) and the Scoop manifest (e7.json) for a release.

    scripts/gen-packaging.py <version> <dir-with-.sha256-files> <out-dir>

The .sha256 files are the ones the release workflow publishes next to each archive
(`<hash>  e7-<version>-<platform>.<ext>`).
"""
import json
import pathlib
import sys

REPO = "https://github.com/e7lang/e7"


def sha_of(d: pathlib.Path, name: str) -> str:
    f = d / f"{name}.sha256"
    h = f.read_text().split()[0].strip().lower()
    if len(h) != 64 or any(c not in "0123456789abcdef" for c in h):
        raise SystemExit(f"bad sha256 in {f}")
    return h


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    version, shadir, out = sys.argv[1].lstrip("v"), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
    out.mkdir(parents=True, exist_ok=True)
    url = f"{REPO}/releases/download/v{version}"
    names = {
        "mac": f"e7-{version}-macos-universal.tar.gz",
        "linux_x64": f"e7-{version}-linux-x64.tar.gz",
        "linux_arm": f"e7-{version}-linux-arm64.tar.gz",
        "win": f"e7-{version}-windows-x64.zip",
    }
    sha = {k: sha_of(shadir, v) for k, v in names.items()}

    formula = f'''# Homebrew formula for the E7 command line tools (generated by scripts/gen-packaging.py).
class E7 < Formula
  desc "Strict TypeScript subset + small verified bytecode VM for embedded scripts"
  homepage "https://e7lang.github.io"
  version "{version}"
  license "MIT"

  on_macos do
    url "{url}/{names['mac']}"
    sha256 "{sha['mac']}"
  end

  on_linux do
    on_arm do
      url "{url}/{names['linux_arm']}"
      sha256 "{sha['linux_arm']}"
    end
    on_intel do
      url "{url}/{names['linux_x64']}"
      sha256 "{sha['linux_x64']}"
    end
  end

  def install
    bin.install "bin/e7", "bin/e7c"
    include.install "include/e7"
    lib.install Dir["lib/*"]
    (share/"e7").install "types", "examples", "bindings"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/e7 --version")
    (testpath/"hello.ts").write 'export function main(): string {{ return "hi " + (40 + 2); }}'
    assert_equal "hi 42", shell_output("#{{bin}}/e7 #{{testpath}}/hello.ts").strip
    system bin/"e7c", testpath/"hello.ts", "-o", testpath/"hello.e7b"
    assert_equal "hi 42", shell_output("#{{bin}}/e7 #{{testpath}}/hello.e7b").strip
  end
end
'''
    (out / "e7.rb").write_text(formula)

    scoop = {
        "version": version,
        "description": "E7: strict TypeScript subset + small verified bytecode VM for embedded scripts",
        "homepage": "https://e7lang.github.io",
        "license": "MIT",
        "architecture": {"64bit": {"url": f"{url}/{names['win']}", "hash": sha["win"],
                                   "extract_dir": f"e7-{version}-windows-x64"}},
        "bin": ["bin\\e7.exe", "bin\\e7c.exe"],
        "checkver": {"github": REPO},
        "autoupdate": {"architecture": {"64bit": {
            "url": f"{REPO}/releases/download/v$version/e7-$version-windows-x64.zip",
            "extract_dir": "e7-$version-windows-x64",
            "hash": {"url": "$url.sha256"}}}},
    }
    (out / "e7.json").write_text(json.dumps(scoop, indent=2) + "\n")
    print(f"wrote {out / 'e7.rb'} and {out / 'e7.json'}")


if __name__ == "__main__":
    main()
