const m = new Map<string, number>([["a", 1], ["b", 2]]);
for (const k of m.keys()) console.log("k", k);
for (const v of m.values()) console.log("v", v);
for (const [k, v] of m.entries()) console.log("e", k, v);
for (const e of m) console.log("t", e[0], e[1]);
